0 || '0' && 1;
/*
result: 1
спочатку обчислюється '0' && 1, тому що у оператора && вищий пріоритет. Повертяється останній true операнд, тобто 1
Потім обчислюється 0 || 1, і повертається перший true операнд, тобто 1
*/

(+null == false) < 1;
