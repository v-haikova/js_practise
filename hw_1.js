true + false;
/*
result: 1
так як true = 1, а false = 0, арифметичне додавання 1 + 0 = 1
*/

'4px' - 3;
/*
result: NaN
js спробує конвертувати рядок '4px' на число, якщо спроба перетворення на число невдала, результат буде NaN
а будь-які операції з NaN повертають NaN
*/

'4' - 3;
/*
result: 1
js конвертує рядок '4' у число, і потім виконає арифметичне віднімання
*/

'6' + 3 ** 0;
/*
result: "61"
у оператора ** вищий пріоритет, тому спочатку 3 возведеться у степінь 0, що буде дорівнювати 1
так як наступний крок це додавання рядка і числа, 1 конвертується у рядок і буде конкатенація рядків '6' + '1'
*/

12 / '6';
/*
result: 2
js конвертує рядок '6' у число, і потім виконає ділення
*/

'10' + (5 === 6);
/*
result: "10false"
5 не дорівнює 6, тому результат буде false
js конвертує false у рядок, і потім виконає конкатенацію 2 рядків
*/

null == '';
/*
result: false
пустий рядок не дорівнює null
*/

3 ** (9 / 3);
